-- =====================================================================
-- Revisao diaria e auditavel das classificacoes por transacao
-- =====================================================================
--
-- Problema:
--   as rotinas atuais mostram apenas fornecedores sem regra ou transacoes
--   enviadas para analise individual. Nao existe uma leitura completa por dia
--   que explique a classificacao final e permita substituir somente a
--   categoria de um lancamento sem alterar o dado importado.
--
-- Solucao:
--   - view protegida sobre fato_financeiro, com origem da classificacao;
--   - historico append-only com autor e estados anterior/posterior;
--   - RPCs dedicadas para classificar, restaurar a base e desfazer;
--   - verificacao otimista para impedir que uma tela antiga sobrescreva uma
--     alteracao mais recente;
--   - refresh dos paineis pela fila assincrona ja existente.
--
-- Riscos controlados:
--   a categoria muda indicadores financeiros derivados. O ajuste continua
--   restrito a public.ajuste_manual; valor, data, origem e tabelas raw nunca
--   sao editados. O estado aparece imediatamente na view normal, enquanto as
--   materialized views sao atualizadas em segundo plano.
-- =====================================================================

begin;

create table if not exists private.transacao_classificacao_historico (
  id bigint generated by default as identity primary key,
  origem text not null,
  raw_id bigint not null,
  data_caixa date not null,
  valor numeric,
  contraparte_nome text,
  acao text not null check (acao in ('classificar', 'restaurar_automatica')),
  categoria_final_anterior text,
  categoria_final_nova text,
  ajuste_anterior text,
  ajuste_anterior_em timestamptz,
  ajuste_anterior_observacao text,
  ajuste_novo text,
  ajuste_novo_em timestamptz,
  ajuste_novo_observacao text,
  alterado_por uuid not null,
  alterado_em timestamptz not null default now(),
  desfeito_por uuid,
  desfeito_em timestamptz,
  check ((desfeito_por is null) = (desfeito_em is null)),
  check ((ajuste_anterior is null) = (ajuste_anterior_em is null)),
  check ((ajuste_novo is null) = (ajuste_novo_em is null))
);

create index if not exists ix_transacao_classificacao_historico_dia
  on private.transacao_classificacao_historico (data_caixa, alterado_em desc);

create index if not exists ix_transacao_classificacao_historico_transacao
  on private.transacao_classificacao_historico
  (origem, raw_id, alterado_em desc);

create index if not exists ix_conciliacao_decisao_estorno_ativo_a
  on public.conciliacao_contabil_decisao (origem_a, raw_id_a)
  where desfeito_em is null and decisao = 'estorno_confirmado';

create index if not exists ix_conciliacao_decisao_estorno_ativo_b
  on public.conciliacao_contabil_decisao (origem_b, raw_id_b)
  where desfeito_em is null and decisao = 'estorno_confirmado';

-- A decisao de estorno e a dona temporaria dos dois ajustes. Triggers
-- diferidos permitem que confirmar/desfazer a conciliacao altere decisao e
-- ajustes na mesma transacao, mas rejeitam qualquer estado final no qual uma
-- decisao ativa nao esteja acompanhada por duas categorias "estornado".
create or replace function private.validar_ponta_estorno_confirmado(
  p_origem text,
  p_raw_id bigint
)
returns void
language plpgsql
security definer
set search_path = pg_catalog, public
as $function$
begin
  if p_origem is null or p_raw_id is null then
    return;
  end if;

  if exists (
    select 1
    from public.conciliacao_contabil_decisao d
    where d.desfeito_em is null
      and d.decisao = 'estorno_confirmado'
      and (
        (d.origem_a = p_origem and d.raw_id_a = p_raw_id)
        or
        (d.origem_b = p_origem and d.raw_id_b = p_raw_id)
      )
  ) and not exists (
    select 1
    from public.ajuste_manual a
    where a.origem = p_origem
      and a.raw_id = p_raw_id
      and a.categoria = 'estornado'
  ) then
    raise exception using errcode = '55000',
      message = 'Esta transacao pertence a um estorno confirmado. Desfaca a decisao na conciliacao contabil antes de alterar a classificacao.';
  end if;
end;
$function$;

create or replace function private.validar_ajuste_estorno_confirmado()
returns trigger
language plpgsql
security definer
set search_path = pg_catalog, public
as $function$
begin
  if tg_op = 'DELETE' then
    perform private.validar_ponta_estorno_confirmado(old.origem, old.raw_id);
  elsif tg_op = 'INSERT' then
    perform private.validar_ponta_estorno_confirmado(new.origem, new.raw_id);
  else
    perform private.validar_ponta_estorno_confirmado(old.origem, old.raw_id);
    if (new.origem, new.raw_id) is distinct from (old.origem, old.raw_id) then
      perform private.validar_ponta_estorno_confirmado(new.origem, new.raw_id);
    end if;
  end if;

  return null;
end;
$function$;

create or replace function private.validar_decisao_estorno_confirmado()
returns trigger
language plpgsql
security definer
set search_path = pg_catalog, public
as $function$
declare
  v_decisao public.conciliacao_contabil_decisao%rowtype;
  v_id bigint;
begin
  if tg_op = 'DELETE' then
    v_id := old.id;
  else
    v_id := new.id;
  end if;

  select *
  into v_decisao
  from public.conciliacao_contabil_decisao d
  where d.id = v_id
    and d.desfeito_em is null
    and d.decisao = 'estorno_confirmado';

  if found then
    perform private.validar_ponta_estorno_confirmado(
      v_decisao.origem_a,
      v_decisao.raw_id_a
    );
    perform private.validar_ponta_estorno_confirmado(
      v_decisao.origem_b,
      v_decisao.raw_id_b
    );
  end if;

  return null;
end;
$function$;

drop trigger if exists ct_ajuste_estorno_confirmado
  on public.ajuste_manual;
create constraint trigger ct_ajuste_estorno_confirmado
after insert or update or delete on public.ajuste_manual
deferrable initially deferred
for each row execute function private.validar_ajuste_estorno_confirmado();

drop trigger if exists ct_decisao_estorno_confirmado
