  select exists (
    select 1
    from private.transacao_classificacao_historico seguinte
    where seguinte.origem = h.origem
      and seguinte.raw_id = h.raw_id
      and seguinte.desfeito_em is null
      and seguinte.id > h.id
  ) as tem_posterior_ativa
) posterior on true
