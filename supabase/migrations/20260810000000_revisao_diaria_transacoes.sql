  select d.id
  from public.conciliacao_contabil_decisao d
  where d.desfeito_em is null
    and d.decisao = 'estorno_confirmado'
    and (
      (d.origem_a = h.origem and d.raw_id_a = h.raw_id)
      or
      (d.origem_b = h.origem and d.raw_id_b = h.raw_id)
    )
  order by d.id desc
  limit 1
) decisao on true
where public.usuario_pode_acessar_pagina('transacoes_dia.html');

