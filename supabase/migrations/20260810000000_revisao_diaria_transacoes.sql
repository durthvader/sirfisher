create or replace view public.app_transacoes_dia
with (security_barrier = true, security_invoker = false) as
select
  f.origem,
  f.raw_id,
  f.empresa,
  f.unidade,
  f.data_caixa,
  f.data_competencia,
  f.movimentacao,
  f.tipo,
  f.valor,
  f.contraparte_nome,
  f.fornecedor,
  f.categoria,
  f.dre_grupo,
  f.status,
  f.natureza,
  f.entra_dre,
  a.categoria as ajuste_atual,
  a.criado_em as ajuste_em,
  case
    when a.id is null then null
    else md5((a.observacao is null)::text || ':' || coalesce(a.observacao, ''))
  end as ajuste_observacao_token,
  decisao.id as conciliacao_decisao_id,
  decisao.ano_mes as conciliacao_ano_mes,
  decisao.id is not null as classificacao_bloqueada,
  case
    when a.id is not null then 'manual'
    when f.categoria is null or f.status in ('analise', 'excecao') then 'pendente'
    when f.origem = 'historico' then 'base_historica'
    else 'automatica'
  end as classificacao_origem
from public.fato_financeiro f
left join public.ajuste_manual a
  on a.origem = f.origem
 and a.raw_id = f.raw_id
left join lateral (
  select d.id, to_char(d.data_a, 'YYYY-MM') as ano_mes
  from public.conciliacao_contabil_decisao d
  where d.desfeito_em is null
    and d.decisao = 'estorno_confirmado'
    and (
      (d.origem_a = f.origem and d.raw_id_a = f.raw_id)
      or
      (d.origem_b = f.origem and d.raw_id_b = f.raw_id)
    )
  order by d.id desc
  limit 1
) decisao on true
where f.data_caixa is not null
  and f.raw_id is not null
  and public.usuario_pode_acessar_pagina('transacoes_dia.html');

