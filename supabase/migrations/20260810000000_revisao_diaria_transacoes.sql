-- Varias correcoes feitas em sequencia compartilham uma unica tarefa pendente,
-- evitando executar o refresh completo das materialized views a cada clique.
create or replace function private.agendar_refresh_classificacoes(
  p_data date
)
returns bigint
language plpgsql
security definer
set search_path = pg_catalog, pg_temp
as $function$
declare
  v_id bigint;
begin
  if p_data is null then
    raise exception using errcode = '22023', message = 'Data do refresh invalida.';
  end if;

  perform pg_catalog.pg_advisory_xact_lock(58000001::bigint);

  select f.id
  into v_id
  from private.fila_recalculo_saldo f
  where f.situacao = 'pendente'
    and f.somente_refresh
  order by f.id
  for update skip locked
  limit 1;

  if v_id is not null then
    update private.fila_recalculo_saldo
    set data_min = least(data_min, p_data),
        data_max = greatest(data_max, p_data),
        mensagem = 'Atualizacao do painel solicitada por classificacoes manuais.'
    where id = v_id;
  else
    insert into private.fila_recalculo_saldo (
      data_min,
      data_max,
      somente_refresh,
      mensagem
    ) values (
      p_data,
      p_data,
      true,
      'Atualizacao do painel solicitada por classificacoes manuais.'
    ) returning id into v_id;
  end if;

  perform cron.schedule(
    'sirfisher-processar-recalculo-saldo',
    '5 seconds',
    'select private.processar_fila_recalculo_saldo();'
  );

  return v_id;
end;
$function$;

revoke all privileges on function private.agendar_refresh_classificacoes(date)
  from public, anon, authenticated;

create or replace function public.salvar_classificacao_transacao_dia(
  p_origem text,
  p_raw_id bigint,
  p_categoria text,
  p_categoria_atual_esperada text,
  p_ajuste_atual_esperado text,
  p_ajuste_em_esperado timestamptz,
  p_ajuste_observacao_token_esperado text
)
returns bigint
language plpgsql
security definer
set search_path = pg_catalog, public
as $function$
declare
  v_data_caixa date;
  v_valor numeric;
  v_contraparte_nome text;
  v_categoria_final text;
  v_ajuste_anterior text;
  v_ajuste_anterior_em timestamptz;
  v_ajuste_anterior_observacao text;
  v_ajuste_observacao_token text;
  v_ajuste_novo_em timestamptz;
  v_ajuste_novo_observacao text;
  v_agora timestamptz := clock_timestamp();
  v_id bigint;
begin
  if not public.usuario_pode_acessar_pagina('transacoes_dia.html') then
    raise exception using errcode = '42501', message = 'Acesso nao autorizado.';
  end if;

  if p_origem is null or btrim(p_origem) = '' or p_raw_id is null then
    raise exception using errcode = '22023', message = 'Transacao invalida.';
  end if;

  if p_categoria is null
     or p_categoria = 'ANALISAR INDIVIDUAL'
     or not exists (
    select 1
    from public.categoria_dre c
    where c.categoria = p_categoria
  ) then
    raise exception using errcode = '22023', message = 'Categoria invalida.';
  end if;

  perform pg_catalog.pg_advisory_xact_lock(
    pg_catalog.hashtextextended(p_origem || ':' || p_raw_id::text, 20260810)
  );

  select
    f.data_caixa,
    f.valor,
    f.contraparte_nome,
    f.categoria,
    a.categoria,
    a.criado_em,
    a.observacao
  into
    v_data_caixa,
    v_valor,
    v_contraparte_nome,
    v_categoria_final,
    v_ajuste_anterior,
    v_ajuste_anterior_em,
    v_ajuste_anterior_observacao
  from public.fato_financeiro f
  left join public.ajuste_manual a
    on a.origem = f.origem
   and a.raw_id = f.raw_id
  where f.origem = p_origem
    and f.raw_id = p_raw_id;

  if not found then
    raise exception using errcode = 'P0002', message = 'Transacao nao encontrada.';
  end if;

  if v_data_caixa is null then
    raise exception using errcode = '22023', message = 'Transacao sem data de caixa.';
  end if;

  v_ajuste_observacao_token := case
    when v_ajuste_anterior is null then null
    else md5(
      (v_ajuste_anterior_observacao is null)::text
      || ':'
      || coalesce(v_ajuste_anterior_observacao, '')
    )
  end;

  if exists (
    select 1
    from public.conciliacao_contabil_decisao d
    where d.desfeito_em is null
      and d.decisao = 'estorno_confirmado'
      and (
        (d.origem_a = p_origem and d.raw_id_a = p_raw_id)
        or
        (d.origem_b = p_origem and d.raw_id_b = p_raw_id)
      )
  ) then
    raise exception using errcode = '55000',
      message = 'Esta transacao pertence a um estorno confirmado. Desfaca a decisao na conciliacao contabil antes de reclassificar.';
  end if;

  if v_categoria_final is distinct from p_categoria_atual_esperada
     or v_ajuste_anterior is distinct from p_ajuste_atual_esperado
     or v_ajuste_anterior_em is distinct from p_ajuste_em_esperado
     or v_ajuste_observacao_token is distinct from p_ajuste_observacao_token_esperado then
    raise exception using errcode = '40001',
      message = 'A transacao foi alterada por outra acao. Atualize a tela antes de salvar.';
  end if;

  if v_ajuste_anterior is not distinct from p_categoria then
    raise exception using errcode = '22023', message = 'A transacao ja possui esse ajuste manual.';
  end if;

  if v_ajuste_anterior is null and v_categoria_final is not distinct from p_categoria then
    raise exception using errcode = '22023', message = 'A transacao ja possui essa classificacao na base.';
  end if;

  if v_ajuste_anterior is null then
    insert into public.ajuste_manual (origem, raw_id, categoria, criado_em)
    values (p_origem, p_raw_id, p_categoria, v_agora)
    on conflict (origem, raw_id) do nothing
    returning criado_em, observacao
    into v_ajuste_novo_em, v_ajuste_novo_observacao;

    if not found then
      raise exception using errcode = '40001',
        message = 'A transacao foi alterada por outra acao. Atualize a tela antes de salvar.';
    end if;
  else
    update public.ajuste_manual
    set categoria = p_categoria,
        criado_em = v_agora
    where origem = p_origem
      and raw_id = p_raw_id
      and categoria is not distinct from v_ajuste_anterior
      and criado_em is not distinct from v_ajuste_anterior_em
      and observacao is not distinct from v_ajuste_anterior_observacao
    returning criado_em, observacao
    into v_ajuste_novo_em, v_ajuste_novo_observacao;

    if not found then
      raise exception using errcode = '40001',
        message = 'A transacao foi alterada por outra acao. Atualize a tela antes de salvar.';
    end if;
  end if;

  insert into private.transacao_classificacao_historico (
    origem,
    raw_id,
    data_caixa,
    valor,
    contraparte_nome,
    acao,
    categoria_final_anterior,
    categoria_final_nova,
    ajuste_anterior,
    ajuste_anterior_em,
    ajuste_anterior_observacao,
    ajuste_novo,
    ajuste_novo_em,
    ajuste_novo_observacao,
    alterado_por,
    alterado_em
  ) values (
    p_origem,
    p_raw_id,
    v_data_caixa,
    v_valor,
    v_contraparte_nome,
    'classificar',
    v_categoria_final,
    p_categoria,
    v_ajuste_anterior,
    v_ajuste_anterior_em,
    v_ajuste_anterior_observacao,
    p_categoria,
    v_ajuste_novo_em,
    v_ajuste_novo_observacao,
    auth.uid(),
    v_agora
  ) returning id into v_id;

  perform private.agendar_refresh_classificacoes(v_data_caixa);

  return v_id;
end;
$function$;

create or replace function public.restaurar_classificacao_transacao_dia(
  p_origem text,
  p_raw_id bigint,
  p_categoria_atual_esperada text,
  p_ajuste_atual_esperado text,
  p_ajuste_em_esperado timestamptz,
  p_ajuste_observacao_token_esperado text
)
returns bigint
language plpgsql
security definer
set search_path = pg_catalog, public
as $function$
declare
  v_data_caixa date;
  v_valor numeric;
  v_contraparte_nome text;
  v_categoria_final text;
  v_categoria_restaurada text;
  v_ajuste_anterior text;
  v_ajuste_anterior_em timestamptz;
  v_ajuste_anterior_observacao text;
  v_ajuste_observacao_token text;
  v_agora timestamptz := clock_timestamp();
  v_id bigint;
begin
  if not public.usuario_pode_acessar_pagina('transacoes_dia.html') then
    raise exception using errcode = '42501', message = 'Acesso nao autorizado.';
  end if;

  if p_origem is null or btrim(p_origem) = '' or p_raw_id is null then
    raise exception using errcode = '22023', message = 'Transacao invalida.';
  end if;

  perform pg_catalog.pg_advisory_xact_lock(
    pg_catalog.hashtextextended(p_origem || ':' || p_raw_id::text, 20260810)
  );

  select
    f.data_caixa,
    f.valor,
    f.contraparte_nome,
    f.categoria,
    a.categoria,
    a.criado_em,
    a.observacao
  into
    v_data_caixa,
    v_valor,
    v_contraparte_nome,
    v_categoria_final,
    v_ajuste_anterior,
    v_ajuste_anterior_em,
    v_ajuste_anterior_observacao
  from public.fato_financeiro f
  left join public.ajuste_manual a
    on a.origem = f.origem
   and a.raw_id = f.raw_id
  where f.origem = p_origem
    and f.raw_id = p_raw_id;

  if not found then
    raise exception using errcode = 'P0002', message = 'Transacao nao encontrada.';
  end if;

  if v_data_caixa is null then
    raise exception using errcode = '22023', message = 'Transacao sem data de caixa.';
  end if;

  v_ajuste_observacao_token := case
    when v_ajuste_anterior is null then null
    else md5(
      (v_ajuste_anterior_observacao is null)::text
      || ':'
      || coalesce(v_ajuste_anterior_observacao, '')
    )
  end;

  if exists (
    select 1
    from public.conciliacao_contabil_decisao d
    where d.desfeito_em is null
      and d.decisao = 'estorno_confirmado'
      and (
        (d.origem_a = p_origem and d.raw_id_a = p_raw_id)
        or
        (d.origem_b = p_origem and d.raw_id_b = p_raw_id)
      )
  ) then
    raise exception using errcode = '55000',
      message = 'Esta transacao pertence a um estorno confirmado. Desfaca a decisao na conciliacao contabil antes de restaurar.';
  end if;

  if v_categoria_final is distinct from p_categoria_atual_esperada
     or v_ajuste_anterior is distinct from p_ajuste_atual_esperado
     or v_ajuste_anterior_em is distinct from p_ajuste_em_esperado
     or v_ajuste_observacao_token is distinct from p_ajuste_observacao_token_esperado then
    raise exception using errcode = '40001',
      message = 'A transacao foi alterada por outra acao. Atualize a tela antes de restaurar.';
  end if;

  if v_ajuste_anterior is null then
    raise exception using errcode = '22023', message = 'A transacao nao possui ajuste manual.';
  end if;

  delete from public.ajuste_manual
  where origem = p_origem
    and raw_id = p_raw_id
    and categoria is not distinct from v_ajuste_anterior
    and criado_em is not distinct from v_ajuste_anterior_em
    and observacao is not distinct from v_ajuste_anterior_observacao;

  if not found then
    raise exception using errcode = '40001',
      message = 'A transacao foi alterada por outra acao. Atualize a tela antes de restaurar.';
  end if;

  select f.categoria
  into v_categoria_restaurada
  from public.fato_financeiro f
  where f.origem = p_origem
    and f.raw_id = p_raw_id;

  if not found then
    raise exception using errcode = 'P0002', message = 'Transacao nao encontrada apos restaurar.';
  end if;

  insert into private.transacao_classificacao_historico (
    origem,
    raw_id,
    data_caixa,
    valor,
    contraparte_nome,
    acao,
    categoria_final_anterior,
    categoria_final_nova,
    ajuste_anterior,
    ajuste_anterior_em,
    ajuste_anterior_observacao,
    ajuste_novo,
    ajuste_novo_em,
    ajuste_novo_observacao,
    alterado_por,
    alterado_em
  ) values (
    p_origem,
    p_raw_id,
    v_data_caixa,
    v_valor,
    v_contraparte_nome,
    'restaurar_automatica',
    v_categoria_final,
    v_categoria_restaurada,
    v_ajuste_anterior,
    v_ajuste_anterior_em,
    v_ajuste_anterior_observacao,
    null,
    null,
    null,
    auth.uid(),
    v_agora
  ) returning id into v_id;

  perform private.agendar_refresh_classificacoes(v_data_caixa);

  return v_id;
end;
$function$;

create or replace function public.desfazer_classificacao_transacao_dia(
  p_historico_id bigint
)
returns void
language plpgsql
security definer
set search_path = pg_catalog, public
as $function$
declare
  v_evento private.transacao_classificacao_historico%rowtype;
  v_ajuste_atual text;
  v_ajuste_atual_em timestamptz;
  v_ajuste_atual_observacao text;
  v_agora timestamptz := clock_timestamp();
begin
  if not public.usuario_pode_acessar_pagina('transacoes_dia.html') then
    raise exception using errcode = '42501', message = 'Acesso nao autorizado.';
  end if;

  select *
  into v_evento
  from private.transacao_classificacao_historico
  where id = p_historico_id
    and desfeito_em is null
  for update;

  if not found then
    raise exception using errcode = 'P0002', message = 'Alteracao ativa nao encontrada.';
  end if;

  if exists (
    select 1
    from private.transacao_classificacao_historico posterior
    where posterior.origem = v_evento.origem
      and posterior.raw_id = v_evento.raw_id
      and posterior.desfeito_em is null
      and posterior.id > v_evento.id
  ) then
    raise exception using errcode = '40001',
      message = 'Existe uma alteracao posterior nesta transacao. Desfaca a mais recente primeiro.';
  end if;

  if exists (
    select 1
    from public.conciliacao_contabil_decisao d
    where d.desfeito_em is null
      and d.decisao = 'estorno_confirmado'
      and (
        (d.origem_a = v_evento.origem and d.raw_id_a = v_evento.raw_id)
        or
        (d.origem_b = v_evento.origem and d.raw_id_b = v_evento.raw_id)
      )
  ) then
    raise exception using errcode = '55000',
      message = 'Esta transacao pertence a um estorno confirmado. Desfaca a decisao na conciliacao contabil antes.';
  end if;

  perform pg_catalog.pg_advisory_xact_lock(
    pg_catalog.hashtextextended(v_evento.origem || ':' || v_evento.raw_id::text, 20260810)
  );

  select a.categoria, a.criado_em, a.observacao
  into v_ajuste_atual, v_ajuste_atual_em, v_ajuste_atual_observacao
  from public.ajuste_manual a
  where a.origem = v_evento.origem
    and a.raw_id = v_evento.raw_id;

  if v_ajuste_atual is distinct from v_evento.ajuste_novo
     or v_ajuste_atual_em is distinct from v_evento.ajuste_novo_em
     or v_ajuste_atual_observacao is distinct from v_evento.ajuste_novo_observacao then
    raise exception using errcode = '40001',
      message = 'A classificacao mudou depois desta acao. Atualize a tela antes de desfazer.';
  end if;

  if v_evento.ajuste_anterior is null then
    delete from public.ajuste_manual
    where origem = v_evento.origem
      and raw_id = v_evento.raw_id
      and categoria is not distinct from v_evento.ajuste_novo
      and criado_em is not distinct from v_evento.ajuste_novo_em
      and observacao is not distinct from v_evento.ajuste_novo_observacao;

    if not found then
      raise exception using errcode = '40001',
        message = 'A classificacao mudou depois desta acao. Atualize a tela antes de desfazer.';
    end if;
  elsif v_evento.ajuste_novo is null then
    insert into public.ajuste_manual (
      origem,
      raw_id,
      categoria,
      criado_em,
      observacao
    )
    values (
      v_evento.origem,
      v_evento.raw_id,
      v_evento.ajuste_anterior,
      v_evento.ajuste_anterior_em,
      v_evento.ajuste_anterior_observacao
    )
    on conflict (origem, raw_id) do nothing;

    if not found then
      raise exception using errcode = '40001',
        message = 'A classificacao mudou depois desta acao. Atualize a tela antes de desfazer.';
    end if;
  else
    update public.ajuste_manual
    set categoria = v_evento.ajuste_anterior,
        criado_em = v_evento.ajuste_anterior_em,
        observacao = v_evento.ajuste_anterior_observacao
    where origem = v_evento.origem
      and raw_id = v_evento.raw_id
      and categoria is not distinct from v_evento.ajuste_novo
      and criado_em is not distinct from v_evento.ajuste_novo_em
      and observacao is not distinct from v_evento.ajuste_novo_observacao;

    if not found then
      raise exception using errcode = '40001',
        message = 'A classificacao mudou depois desta acao. Atualize a tela antes de desfazer.';
    end if;
  end if;

  update private.transacao_classificacao_historico
  set desfeito_por = auth.uid(),
      desfeito_em = v_agora
  where id = v_evento.id;

  perform private.agendar_refresh_classificacoes(v_evento.data_caixa);
end;
$function$;

