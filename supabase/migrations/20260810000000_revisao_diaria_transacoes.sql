  h.desfeito_em is null
    and not posterior.tem_posterior_ativa
    and atual.categoria is not distinct from h.ajuste_novo
    and atual.criado_em is not distinct from h.ajuste_novo_em
    and atual.observacao is not distinct from h.ajuste_novo_observacao
    and decisao.id is null
