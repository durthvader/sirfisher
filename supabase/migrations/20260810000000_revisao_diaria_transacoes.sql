create constraint trigger ct_decisao_estorno_confirmado
after insert or update or delete on public.conciliacao_contabil_decisao
deferrable initially deferred
for each row execute function private.validar_decisao_estorno_confirmado();

-- Nao corrige dados financeiros silenciosamente. Se um fluxo antigo ja tiver
-- quebrado uma decisao ativa, a migration para e informa que o caso precisa de
-- revisao consciente antes de instalar a nova garantia.
do $migration$
declare
  v_inconsistentes bigint;
begin
  select count(*)
  into v_inconsistentes
  from public.conciliacao_contabil_decisao d
  where d.desfeito_em is null
    and d.decisao = 'estorno_confirmado'
    and (
      not exists (
        select 1
        from public.ajuste_manual a
        where a.origem = d.origem_a
          and a.raw_id = d.raw_id_a
          and a.categoria = 'estornado'
      )
      or not exists (
        select 1
        from public.ajuste_manual a
        where a.origem = d.origem_b
          and a.raw_id = d.raw_id_b
          and a.categoria = 'estornado'
      )
    );

  if v_inconsistentes > 0 then
    raise exception using errcode = '55000',
      message = format(
        'Existem %s decisoes ativas de estorno sem as duas pontas classificadas como estornado. Revise esses casos antes de aplicar esta migration.',
        v_inconsistentes
      );
  end if;
end;
$migration$;

