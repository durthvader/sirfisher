create or replace function public.listar_regras_de_para(
  p_busca text default null,
  p_status text default 'ativas',
  p_categoria text default null,
  p_chave_tipo text default null,
  p_pagina integer default 1,
  p_tamanho_pagina integer default 30
)
returns jsonb
language plpgsql
stable
security definer
set search_path = pg_catalog, public
as $function$
declare
  v_busca text := nullif(btrim(p_busca), '');
  v_busca_digitos text := case
    when nullif(btrim(p_busca), '') ~ '[0-9]' then public.so_digitos(p_busca)
    else null
  end;
  v_status text := coalesce(nullif(btrim(p_status), ''), 'ativas');
  v_pagina integer := greatest(coalesce(p_pagina, 1), 1);
  v_tamanho integer := least(greatest(coalesce(p_tamanho_pagina, 30), 1), 100);
  v_resultado jsonb;
begin
  if not public.usuario_pode_acessar_pagina('gerenciador_de_para.html') then
    raise exception using errcode = '42501', message = 'Acesso nao autorizado.';
  end if;

  if v_status not in ('ativas', 'inativas', 'todas') then
    raise exception using errcode = '22023', message = 'Filtro de status invalido.';
  end if;

  if p_chave_tipo is not null and p_chave_tipo not in ('nome', 'cnpj') then
    raise exception using errcode = '22023', message = 'Tipo de chave invalido.';
  end if;

  with filtradas as materialized (
    select
      d.id,
      d.chave_tipo,
      d.chave_valor,
      d.fornecedor,
      d.categoria,
      c.dre_grupo,
      c.natureza,
      d.ativo,
      d.atualizado_em,
      private.token_estado_de_para(
        d.id,
        d.chave_tipo,
        d.chave_valor,
        d.fornecedor,
        d.categoria,
        d.ativo,
        d.atualizado_em
      ) as estado_token
    from public.de_para d
    left join public.categoria_dre c
      on c.categoria = d.categoria
    where (v_status = 'todas'
      or (v_status = 'ativas' and d.ativo)
      or (v_status = 'inativas' and not d.ativo))
      and (p_categoria is null or d.categoria = p_categoria)
      and (p_chave_tipo is null or d.chave_tipo = p_chave_tipo)
      and (
        v_busca is null
        or coalesce(d.fornecedor, '') ilike '%' || v_busca || '%'
        or d.chave_valor ilike '%' || v_busca || '%'
        or (
          d.chave_tipo = 'cnpj'
          and v_busca_digitos is not null
          and d.chave_valor ilike '%' || v_busca_digitos || '%'
        )
        or d.categoria ilike '%' || v_busca || '%'
      )
  ),
  pagina as (
    select f.*
    from filtradas f
    order by f.ativo desc, coalesce(f.fornecedor, f.chave_valor), f.id
    limit v_tamanho
    offset (v_pagina - 1)::bigint * v_tamanho::bigint
  )
  select jsonb_build_object(
    'itens', coalesce(
      (
        select jsonb_agg(
          jsonb_build_object(
            'id', p.id,
            'chave_tipo', p.chave_tipo,
            'chave_valor', p.chave_valor,
            'fornecedor', p.fornecedor,
            'categoria', p.categoria,
            'dre_grupo', p.dre_grupo,
            'natureza', p.natureza,
            'ativo', p.ativo,
            'atualizado_em', p.atualizado_em,
            'estado_token', p.estado_token
          )
          order by p.ativo desc, coalesce(p.fornecedor, p.chave_valor), p.id
        )
        from pagina p
      ),
      '[]'::jsonb
    ),
    'total_filtrado', (select count(*) from filtradas),
    'total_ativas', (select count(*) from public.de_para d where d.ativo),
    'total_inativas', (select count(*) from public.de_para d where not d.ativo),
    'pagina', v_pagina,
    'tamanho_pagina', v_tamanho
  ) into v_resultado;

  return v_resultado;
end;
$function$;

create or replace function public.prever_alteracao_de_para(
  p_id bigint,
  p_fornecedor text,
  p_categoria text,
  p_ativo boolean,
  p_estado_token_esperado text
)
returns jsonb
language plpgsql
security definer
set search_path = pg_catalog, public
as $function$
declare
  v_regra public.de_para%rowtype;
  v_fornecedor text := nullif(btrim(p_fornecedor), '');
  v_token_atual text;
  v_antes jsonb := '[]'::jsonb;
  v_depois jsonb := '[]'::jsonb;
  v_correspondencias bigint := 0;
  v_ajustes_manuais bigint := 0;
  v_classificacoes bigint := 0;
  v_rotulos bigint := 0;
  v_impactadas bigint := 0;
  v_entradas numeric := 0;
  v_saidas numeric := 0;
  v_data_min date;
  v_data_max date;
  v_transicoes jsonb := '[]'::jsonb;
begin
  if not public.usuario_pode_acessar_pagina('gerenciador_de_para.html') then
    raise exception using errcode = '42501', message = 'Acesso nao autorizado.';
  end if;

  if p_id is null or p_ativo is null or p_estado_token_esperado is null then
    raise exception using errcode = '22023', message = 'Estado da regra incompleto.';
  end if;

  if v_fornecedor is null or char_length(v_fornecedor) > 120 then
    raise exception using errcode = '22023',
      message = 'O nome de exibicao e obrigatorio e deve ter ate 120 caracteres.';
  end if;

  if not exists (
    select 1 from public.categoria_dre c where c.categoria = p_categoria
  ) then
    raise exception using errcode = '22023', message = 'Categoria invalida.';
  end if;

  perform pg_catalog.pg_advisory_xact_lock(58000002::bigint);

  select d.*
  into v_regra
  from public.de_para d
  where d.id = p_id
  for update;

  if not found then
    raise exception using errcode = 'P0002', message = 'Regra De/Para nao encontrada.';
  end if;

  v_token_atual := private.token_estado_de_para(
    v_regra.id,
    v_regra.chave_tipo,
    v_regra.chave_valor,
    v_regra.fornecedor,
    v_regra.categoria,
    v_regra.ativo,
    v_regra.atualizado_em
  );

  if v_token_atual is distinct from p_estado_token_esperado then
    raise exception using errcode = '40001',
      message = 'Esta regra mudou desde que a tela foi carregada. Atualize a lista e tente novamente.';
  end if;

  if row(v_regra.fornecedor, v_regra.categoria, v_regra.ativo)
       is not distinct from row(v_fornecedor, p_categoria, p_ativo) then
    raise exception using errcode = '22023', message = 'Nenhuma alteracao foi informada.';
  end if;

  select coalesce(
    jsonb_agg(
      jsonb_build_object(
        'origem', f.origem,
        'raw_id', f.raw_id::text,
        'data_caixa', f.data_caixa,
        'valor', f.valor,
        'categoria', f.categoria,
        'dre_grupo', f.dre_grupo,
        'status', f.status,
        'entra_dre', f.entra_dre,
        'fornecedor', f.fornecedor,
        'manual', a.id is not null,
        'fonte_token', md5(jsonb_build_array(
          f.data_caixa,
          f.valor,
          f.movimentacao,
          f.tipo,
          f.contraparte_nome,
          f.contraparte_doc
        )::text),
        'ajuste_token', case when a.id is null then null else md5(
          jsonb_build_array(a.categoria, a.criado_em, a.observacao)::text
        ) end
      ) order by f.origem, f.raw_id
    ),
    '[]'::jsonb
  )
  into v_antes
  from public.fato_financeiro f
  left join public.ajuste_manual a
    on a.origem = f.origem
   and a.raw_id = f.raw_id
  where f.origem <> 'historico'
    and (
      (
        v_regra.chave_tipo = 'cnpj'
        and f.contraparte_doc like '%/%'
        and f.contraparte_doc not like '%*%'
        and public.so_digitos(f.contraparte_doc) = v_regra.chave_valor
      )
      or
      (
        v_regra.chave_tipo = 'nome'
        and f.contraparte_nome is not null
        and f.contraparte_nome not ilike 'desconhecido'
        and public.normaliza_nome(f.contraparte_nome) = v_regra.chave_valor
      )
    );

  perform pg_catalog.set_config('sirfisher.de_para_contexto', 'preview', true);

  -- O erro proposital encerra a subtransacao e desfaz tanto o UPDATE quanto
  -- qualquer efeito do trigger. Variaveis PL/pgSQL mantem a fotografia lida.
  begin
    update public.de_para
    set fornecedor = v_fornecedor,
        categoria = p_categoria,
        ativo = p_ativo,
        atualizado_em = clock_timestamp()
    where id = v_regra.id;

    select coalesce(
      jsonb_agg(
        jsonb_build_object(
          'origem', f.origem,
          'raw_id', f.raw_id::text,
          'data_caixa', f.data_caixa,
          'valor', f.valor,
          'categoria', f.categoria,
          'dre_grupo', f.dre_grupo,
          'status', f.status,
          'entra_dre', f.entra_dre,
          'fornecedor', f.fornecedor,
          'manual', a.id is not null,
          'fonte_token', md5(jsonb_build_array(
            f.data_caixa,
            f.valor,
            f.movimentacao,
            f.tipo,
            f.contraparte_nome,
            f.contraparte_doc
          )::text),
          'ajuste_token', case when a.id is null then null else md5(
            jsonb_build_array(a.categoria, a.criado_em, a.observacao)::text
          ) end
        ) order by f.origem, f.raw_id
      ),
      '[]'::jsonb
    )
    into v_depois
    from public.fato_financeiro f
    left join public.ajuste_manual a
      on a.origem = f.origem
     and a.raw_id = f.raw_id
    where f.origem <> 'historico'
      and (
        (
          v_regra.chave_tipo = 'cnpj'
          and f.contraparte_doc like '%/%'
          and f.contraparte_doc not like '%*%'
          and public.so_digitos(f.contraparte_doc) = v_regra.chave_valor
        )
        or
        (
          v_regra.chave_tipo = 'nome'
          and f.contraparte_nome is not null
          and f.contraparte_nome not ilike 'desconhecido'
          and public.normaliza_nome(f.contraparte_nome) = v_regra.chave_valor
        )
      );

    raise exception using errcode = 'PZ001', message = 'rollback da previa';
  exception
    when sqlstate 'PZ001' then null;
  end;

  -- Importacoes e ajustes nao usam o lock do De/Para. Se algum deles mudar
  -- entre as duas fotografias, a previa e repetida em vez de atribuir essa
  -- concorrencia a regra simulada.
  if exists (
    with antes as (
      select *
      from jsonb_to_recordset(v_antes) as x(
        origem text,
        raw_id text,
        data_caixa date,
        valor numeric,
        categoria text,
        dre_grupo text,
        status text,
        entra_dre boolean,
        fornecedor text,
        manual boolean,
        fonte_token text,
        ajuste_token text
      )
    ),
    depois as (
      select *
      from jsonb_to_recordset(v_depois) as x(
        origem text,
        raw_id text,
        data_caixa date,
        valor numeric,
        categoria text,
        dre_grupo text,
        status text,
        entra_dre boolean,
        fornecedor text,
        manual boolean,
        fonte_token text,
        ajuste_token text
      )
    )
    select 1
    from antes a
    full join depois d
      on d.origem = a.origem
     and d.raw_id = a.raw_id
    where a.origem is null
       or d.origem is null
       or a.fonte_token is distinct from d.fonte_token
       or a.ajuste_token is distinct from d.ajuste_token
  ) then
    raise exception using errcode = '40001',
      message = 'Os lancamentos mudaram durante a previa. Revise o impacto novamente.';
  end if;

  with antes as (
    select *
    from jsonb_to_recordset(v_antes) as x(
      origem text,
      raw_id text,
      data_caixa date,
      valor numeric,
      categoria text,
      dre_grupo text,
      status text,
      entra_dre boolean,
      fornecedor text,
      manual boolean,
      fonte_token text,
      ajuste_token text
    )
  ),
  depois as (
    select *
    from jsonb_to_recordset(v_depois) as x(
      origem text,
      raw_id text,
      data_caixa date,
      valor numeric,
      categoria text,
      dre_grupo text,
      status text,
      entra_dre boolean,
      fornecedor text,
      manual boolean,
      fonte_token text,
      ajuste_token text
    )
  ),
  comparacao as (
    select
      coalesce(a.origem, d.origem) as origem,
      coalesce(a.raw_id, d.raw_id) as raw_id,
      coalesce(a.data_caixa, d.data_caixa) as data_caixa,
      coalesce(a.valor, d.valor) as valor,
      coalesce(a.manual, d.manual, false) as manual,
      a.categoria as categoria_antes,
      d.categoria as categoria_depois,
      a.status as status_antes,
      d.status as status_depois,
      (
        row(a.categoria, a.dre_grupo, a.status, a.entra_dre)
          is distinct from
        row(d.categoria, d.dre_grupo, d.status, d.entra_dre)
      ) as classificacao_mudou,
      a.fornecedor is distinct from d.fornecedor as rotulo_mudou
    from antes a
    full join depois d
      on d.origem = a.origem
     and d.raw_id = a.raw_id
  )
  select
    count(*),
    count(*) filter (where c.manual),
    count(*) filter (where not c.manual and c.classificacao_mudou),
    count(*) filter (where c.rotulo_mudou),
    count(*) filter (where c.classificacao_mudou or c.rotulo_mudou),
    coalesce(sum(c.valor) filter (
      where (c.classificacao_mudou or c.rotulo_mudou) and c.valor > 0
    ), 0),
    coalesce(abs(sum(c.valor) filter (
      where (c.classificacao_mudou or c.rotulo_mudou) and c.valor < 0
    )), 0),
    min(c.data_caixa) filter (where c.classificacao_mudou or c.rotulo_mudou),
    max(c.data_caixa) filter (where c.classificacao_mudou or c.rotulo_mudou)
  into
    v_correspondencias,
    v_ajustes_manuais,
    v_classificacoes,
    v_rotulos,
    v_impactadas,
    v_entradas,
    v_saidas,
    v_data_min,
    v_data_max
  from comparacao c;

  with antes as (
    select *
    from jsonb_to_recordset(v_antes) as x(
      origem text,
      raw_id text,
      data_caixa date,
      valor numeric,
      categoria text,
      dre_grupo text,
      status text,
      entra_dre boolean,
      fornecedor text,
      manual boolean,
      fonte_token text,
      ajuste_token text
    )
  ),
  depois as (
    select *
    from jsonb_to_recordset(v_depois) as x(
      origem text,
      raw_id text,
      data_caixa date,
      valor numeric,
      categoria text,
      dre_grupo text,
      status text,
      entra_dre boolean,
      fornecedor text,
      manual boolean,
      fonte_token text,
      ajuste_token text
    )
  ),
  agrupado as (
    select
      coalesce(a.categoria, 'Sem categoria') as categoria_antes,
      coalesce(d.categoria, 'Sem categoria') as categoria_depois,
      coalesce(a.status, 'sem status') as status_antes,
      coalesce(d.status, 'sem status') as status_depois,
      count(*) as quantidade
    from antes a
    join depois d
      on d.origem = a.origem
     and d.raw_id = a.raw_id
    where not coalesce(a.manual, false)
      and row(a.categoria, a.dre_grupo, a.status, a.entra_dre)
        is distinct from
          row(d.categoria, d.dre_grupo, d.status, d.entra_dre)
    group by a.categoria, d.categoria, a.status, d.status
  )
  select coalesce(
    jsonb_agg(
      jsonb_build_object(
        'categoria_antes', g.categoria_antes,
        'categoria_depois', g.categoria_depois,
        'status_antes', g.status_antes,
        'status_depois', g.status_depois,
        'quantidade', g.quantidade
      ) order by g.quantidade desc, g.categoria_antes, g.categoria_depois
    ),
    '[]'::jsonb
  )
  into v_transicoes
  from agrupado g;

  return jsonb_build_object(
    'regra_id', v_regra.id,
    'qtd_correspondencias', v_correspondencias,
    'qtd_ajustes_manuais', v_ajustes_manuais,
    'qtd_classificacao_alterada', v_classificacoes,
    'qtd_rotulo_alterado', v_rotulos,
    'qtd_impactadas', v_impactadas,
    'entradas_afetadas', v_entradas,
    'saidas_afetadas', v_saidas,
    'data_min', v_data_min,
    'data_max', v_data_max,
    'transicoes', v_transicoes,
    'impacto_token', md5(
      jsonb_build_array(
        v_token_atual,
        v_fornecedor,
        p_categoria,
        p_ativo,
        v_antes,
        v_depois
      )::text
    ),
    'historico_consolidado_alterado', false
  );
end;
$function$;

create or replace function public.salvar_regra_de_para(
  p_id bigint,
  p_fornecedor text,
  p_categoria text,
  p_ativo boolean,
  p_estado_token_esperado text,
  p_impacto_token_esperado text
)
returns jsonb
language plpgsql
security definer
set search_path = pg_catalog, public
as $function$
declare
  v_regra public.de_para%rowtype;
  v_nova public.de_para%rowtype;
  v_fornecedor text := nullif(btrim(p_fornecedor), '');
  v_token_atual text;
  v_previa jsonb;
begin
  if not public.usuario_pode_acessar_pagina('gerenciador_de_para.html') then
    raise exception using errcode = '42501', message = 'Acesso nao autorizado.';
  end if;

  if p_id is null
     or p_ativo is null
     or p_estado_token_esperado is null
     or p_impacto_token_esperado is null then
    raise exception using errcode = '22023', message = 'Estado da regra incompleto.';
  end if;

  if v_fornecedor is null or char_length(v_fornecedor) > 120 then
    raise exception using errcode = '22023',
      message = 'O nome de exibicao e obrigatorio e deve ter ate 120 caracteres.';
  end if;

  if not exists (
    select 1 from public.categoria_dre c where c.categoria = p_categoria
  ) then
    raise exception using errcode = '22023', message = 'Categoria invalida.';
  end if;

  -- A confirmacao recalcula a mesma fotografia. Importacoes ou ajustes feitos
  -- depois da previa invalidam o token e exigem nova revisao na tela.
  v_previa := public.prever_alteracao_de_para(
    p_id,
    v_fornecedor,
    p_categoria,
    p_ativo,
    p_estado_token_esperado
  );

  if v_previa ->> 'impacto_token' is distinct from p_impacto_token_esperado then
    raise exception using errcode = '40001',
      message = 'O impacto mudou desde a previa. Revise os dados novamente antes de confirmar.';
  end if;

  perform pg_catalog.pg_advisory_xact_lock(58000002::bigint);

  select d.*
  into v_regra
  from public.de_para d
  where d.id = p_id
  for update;

  if not found then
    raise exception using errcode = 'P0002', message = 'Regra De/Para nao encontrada.';
  end if;

  v_token_atual := private.token_estado_de_para(
    v_regra.id,
    v_regra.chave_tipo,
    v_regra.chave_valor,
    v_regra.fornecedor,
    v_regra.categoria,
    v_regra.ativo,
    v_regra.atualizado_em
  );

  if v_token_atual is distinct from p_estado_token_esperado then
    raise exception using errcode = '40001',
      message = 'Esta regra mudou desde que a tela foi carregada. Atualize a lista e tente novamente.';
  end if;

  if row(v_regra.fornecedor, v_regra.categoria, v_regra.ativo)
       is not distinct from row(v_fornecedor, p_categoria, p_ativo) then
    raise exception using errcode = '22023', message = 'Nenhuma alteracao foi informada.';
  end if;

  perform pg_catalog.set_config('sirfisher.de_para_contexto', 'gerenciador', true);

  update public.de_para
  set fornecedor = v_fornecedor,
      categoria = p_categoria,
      ativo = p_ativo,
      atualizado_em = clock_timestamp()
  where id = v_regra.id
  returning * into v_nova;

  perform private.agendar_refresh_classificacoes(current_date);

  return jsonb_build_object(
    'id', v_nova.id,
    'estado_token', private.token_estado_de_para(
      v_nova.id,
      v_nova.chave_tipo,
      v_nova.chave_valor,
      v_nova.fornecedor,
      v_nova.categoria,
      v_nova.ativo,
      v_nova.atualizado_em
    )
  );
end;
$function$;

create or replace function private.desfazer_evento_de_para(
  p_historico_id bigint
)
returns bigint
language plpgsql
security definer
set search_path = pg_catalog, public
as $function$
declare
  v_evento private.de_para_historico%rowtype;
  v_atual public.de_para%rowtype;
  v_existe_atual boolean := false;
begin
  if p_historico_id is null then
    raise exception using errcode = '22023', message = 'Alteracao invalida.';
  end if;

  perform pg_catalog.pg_advisory_xact_lock(58000002::bigint);

  select h.*
  into v_evento
  from private.de_para_historico h
  where h.id = p_historico_id
  for update;

  if not found then
    raise exception using errcode = 'P0002', message = 'Alteracao nao encontrada.';
  end if;

  if v_evento.desfeito_em is not null then
    raise exception using errcode = '55000', message = 'Esta alteracao ja foi desfeita.';
  end if;

  if v_evento.alterado_por is null or v_evento.origem_acao = 'sistema' then
    raise exception using errcode = '42501',
      message = 'Alteracoes tecnicas do sistema nao podem ser desfeitas por esta rotina.';
  end if;

  if exists (
    select 1
    from private.de_para_historico posterior
    where posterior.chave_tipo = v_evento.chave_tipo
      and posterior.chave_valor = v_evento.chave_valor
      and posterior.id > v_evento.id
      and posterior.desfeito_em is null
  ) then
    raise exception using errcode = '55000',
      message = 'Existe uma alteracao posterior ativa para esta regra.';
  end if;

  select d.*
  into v_atual
  from public.de_para d
  where d.id = v_evento.regra_id
  for update;
  v_existe_atual := found;

  if v_evento.existia_depois then
    if not v_existe_atual
       or row(v_atual.chave_tipo, v_atual.chave_valor, v_atual.fornecedor, v_atual.categoria, v_atual.ativo)
         is distinct from
          row(v_evento.chave_tipo, v_evento.chave_valor, v_evento.fornecedor_depois, v_evento.categoria_depois, v_evento.ativo_depois) then
      raise exception using errcode = '40001',
        message = 'O estado atual da regra nao corresponde mais a esta alteracao.';
    end if;
  elsif v_existe_atual then
    raise exception using errcode = '40001',
      message = 'A regra foi recriada depois desta alteracao.';
  end if;

  perform pg_catalog.set_config('sirfisher.de_para_contexto', 'desfazer', true);

  if v_evento.existia_antes then
    if v_existe_atual then
      update public.de_para
      set fornecedor = v_evento.fornecedor_antes,
          categoria = v_evento.categoria_antes,
          ativo = v_evento.ativo_antes,
          atualizado_em = v_evento.atualizado_em_antes
      where id = v_evento.regra_id;
    else
      insert into public.de_para (
        id,
        chave_tipo,
        chave_valor,
        fornecedor,
        categoria,
        ativo,
        atualizado_em
      ) values (
        v_evento.regra_id,
        v_evento.chave_tipo,
        v_evento.chave_valor,
        v_evento.fornecedor_antes,
        v_evento.categoria_antes,
        v_evento.ativo_antes,
        v_evento.atualizado_em_antes
      );
    end if;
  elsif v_existe_atual then
    -- Desfazer a criacao restaura a inexistencia exata. Esta e a unica
    -- exclusao do fluxo e ocorre sob lock, vinculada ao evento auditado.
    delete from public.de_para
    where id = v_evento.regra_id;
  end if;

  update private.de_para_historico
  set desfeito_por = auth.uid(),
      desfeito_em = clock_timestamp()
  where id = v_evento.id;

  perform private.agendar_refresh_classificacoes(current_date);

  return v_evento.regra_id;
end;
$function$;

revoke all privileges on function private.desfazer_evento_de_para(bigint)
  from public, anon, authenticated;

