-- A fila de excecoes continua responsavel por criar/reclassificar uma chave,
-- agora passando pela mesma auditoria e pelo refresh assincrono.
create or replace function public.classificar_excecao(
  p_chave_tipo text,
  p_chave_valor text,
  p_fornecedor text,
  p_categoria text
)
returns bigint
language plpgsql
security definer
set search_path = pg_catalog, public
as $function$
declare
  v_id bigint;
  v_chave_valor text := btrim(p_chave_valor);
  v_fornecedor text := coalesce(nullif(btrim(p_fornecedor), ''), btrim(p_chave_valor));
  v_existente public.de_para%rowtype;
  v_existe boolean := false;
begin
  if not public.usuario_pode_acessar_pagina('classificar_excecoes.html') then
    raise exception using errcode = '42501', message = 'Acesso nao autorizado.';
  end if;

  if p_chave_tipo is null
     or p_chave_tipo not in ('nome', 'cnpj')
     or v_chave_valor is null
     or v_chave_valor = '' then
    raise exception using errcode = '22023', message = 'Chave de classificacao invalida.';
  end if;

  if not exists (
    select 1 from public.categoria_dre c where c.categoria = p_categoria
  ) then
    raise exception using errcode = '22023', message = 'Categoria invalida.';
  end if;

  perform pg_catalog.pg_advisory_xact_lock(58000002::bigint);

  select d.*
  into v_existente
  from public.de_para d
  where d.chave_tipo = p_chave_tipo
    and d.chave_valor = v_chave_valor
  for update;
  v_existe := found;

  -- Uma resposta repetida da mesma classificacao e idempotente. Qualquer
  -- mudanca em regra ativa pertence ao gerenciador e exige previa/token.
  if v_existe and v_existente.ativo then
    if row(v_existente.fornecedor, v_existente.categoria)
         is not distinct from row(v_fornecedor, p_categoria) then
      return v_existente.id;
    end if;

    raise exception using errcode = '42501',
      message = 'Esta regra ja esta ativa. Use o Gerenciador De/Para para altera-la.';
  end if;

  if not exists (
    select 1
    from public.excecoes e
    where e.chave_tipo = p_chave_tipo
      and e.chave_valor = v_chave_valor
  ) then
    raise exception using errcode = '42501',
      message = 'Esta chave nao esta mais na fila de excecoes. Atualize a pagina antes de salvar.';
  end if;

  perform pg_catalog.set_config('sirfisher.de_para_contexto', 'classificar_excecoes', true);

  insert into public.de_para (
    chave_tipo,
    chave_valor,
    fornecedor,
    categoria,
    ativo,
    atualizado_em
  ) values (
    p_chave_tipo,
    v_chave_valor,
    v_fornecedor,
    p_categoria,
    true,
    clock_timestamp()
  )
  on conflict (chave_tipo, chave_valor) do update
    set fornecedor = excluded.fornecedor,
        categoria = excluded.categoria,
        ativo = true,
        atualizado_em = clock_timestamp()
  returning id into v_id;

  perform private.agendar_refresh_classificacoes(current_date);

  return v_id;
end;
$function$;

create or replace function public.corrigir_classificacao(
  p_tipo text,
  p_id bigint,
  p_categoria text
)
returns void
language plpgsql
security definer
set search_path = pg_catalog, public
as $function$
declare
  v_afetadas integer;
begin
  if not coalesce(
    (p_tipo = 'excecao' and public.usuario_pode_acessar_pagina('gerenciador_de_para.html'))
    or
    (p_tipo = 'individual' and public.usuario_pode_acessar_pagina('analise_individual.html')),
    false
  ) then
    raise exception using errcode = '42501', message = 'Acesso nao autorizado.';
  end if;

  if not exists (
    select 1 from public.categoria_dre c where c.categoria = p_categoria
  ) then
    raise exception using errcode = '22023', message = 'Categoria invalida.';
  end if;

  if p_tipo = 'excecao' then
    raise exception using errcode = '0A000',
      message = 'Use o Gerenciador De/Para para alterar regras por fornecedor.';
  elsif p_tipo = 'individual' then
    update public.ajuste_manual
    set categoria = p_categoria,
        criado_em = clock_timestamp()
    where id = p_id;
  else
    raise exception using errcode = '22023', message = 'Tipo de classificacao invalido.';
  end if;

  get diagnostics v_afetadas = row_count;
  if v_afetadas = 0 then
    raise exception using errcode = 'P0002', message = 'Classificacao nao encontrada.';
  end if;

  perform private.agendar_refresh_classificacoes(current_date);
end;
$function$;

create or replace function public.desfazer_classificacao(
  p_tipo text,
  p_id bigint
)
returns void
language plpgsql
security definer
set search_path = pg_catalog, public
as $function$
declare
  v_afetadas integer;
  v_historico_id bigint;
  v_pode_gerenciar boolean := public.usuario_pode_acessar_pagina('gerenciador_de_para.html');
begin
  if not coalesce(
    (p_tipo = 'excecao' and (
      v_pode_gerenciar
      or public.usuario_pode_acessar_pagina('classificar_excecoes.html')
    ))
    or
    (p_tipo = 'individual' and public.usuario_pode_acessar_pagina('analise_individual.html')),
    false
  ) then
    raise exception using errcode = '42501', message = 'Acesso nao autorizado.';
  end if;

  if p_tipo = 'excecao' then
    select h.id
    into v_historico_id
    from private.de_para_historico h
    where h.regra_id = p_id
      and h.desfeito_em is null
      and h.origem_acao = 'classificar_excecoes'
      and h.alterado_por = auth.uid()
      and h.alterado_em >= clock_timestamp() - interval '10 minutes'
    order by h.id desc
    limit 1;

    if v_historico_id is not null then
      perform private.desfazer_evento_de_para(v_historico_id);
      return;
    end if;

    raise exception using errcode = '42501',
      message = 'O prazo do desfazer imediato terminou. Use o Gerenciador De/Para.';
  elsif p_tipo = 'individual' then
    delete from public.ajuste_manual where id = p_id;
  else
    raise exception using errcode = '22023', message = 'Tipo de classificacao invalido.';
  end if;

  if p_tipo = 'individual' then
    get diagnostics v_afetadas = row_count;
    if v_afetadas = 0 then
      raise exception using errcode = 'P0002', message = 'Classificacao nao encontrada.';
    end if;
  end if;

  perform private.agendar_refresh_classificacoes(current_date);
end;
$function$;

create or replace view public.app_gerenciador_de_para_historico
with (security_barrier = true, security_invoker = false) as
select
  h.id,
  h.regra_id,
  h.chave_tipo,
  h.chave_valor,
  h.acao,
  h.origem_acao,
  h.existia_antes,
  h.fornecedor_antes,
  h.categoria_antes,
  h.ativo_antes,
  h.existia_depois,
  h.fornecedor_depois,
  h.categoria_depois,
  h.ativo_depois,
  private.nome_exibicao_usuario(h.alterado_por) as alterado_por_nome,
  h.alterado_em,
  h.desfeito_em is not null as desfeita,
  posterior.tem_posterior_ativa,
  h.desfeito_em is null
    and not posterior.tem_posterior_ativa
    and (
      (h.existia_depois and atual.id is not null
        and atual.chave_tipo = h.chave_tipo
        and atual.chave_valor = h.chave_valor
        and atual.fornecedor is not distinct from h.fornecedor_depois
        and atual.categoria is not distinct from h.categoria_depois
        and atual.ativo is not distinct from h.ativo_depois)
      or
      (not h.existia_depois and atual.id is null)
    ) as eh_estado_atual,
  h.desfeito_em is null
    and not posterior.tem_posterior_ativa
    and h.alterado_por is not null
    and h.origem_acao <> 'sistema'
    and (
      (h.existia_depois and atual.id is not null
        and atual.chave_tipo = h.chave_tipo
        and atual.chave_valor = h.chave_valor
        and atual.fornecedor is not distinct from h.fornecedor_depois
        and atual.categoria is not distinct from h.categoria_depois
        and atual.ativo is not distinct from h.ativo_depois)
      or
      (not h.existia_depois and atual.id is null)
    ) as pode_desfazer,
  private.nome_exibicao_usuario(h.desfeito_por) as desfeito_por_nome,
  h.desfeito_em
from private.de_para_historico h
left join public.de_para atual
  on atual.id = h.regra_id
left join lateral (
  select exists (
    select 1
    from private.de_para_historico seguinte
    where seguinte.chave_tipo = h.chave_tipo
      and seguinte.chave_valor = h.chave_valor
      and seguinte.id > h.id
      and seguinte.desfeito_em is null
  ) as tem_posterior_ativa
) posterior on true
where public.usuario_pode_acessar_pagina('gerenciador_de_para.html');

