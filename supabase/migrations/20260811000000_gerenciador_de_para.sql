-- =====================================================================
-- Gerenciador auditavel das regras De/Para
-- =====================================================================
--
-- Problema:
--   as regras por nome/CNPJ so podiam ser criadas na fila de excecoes. Para
--   corrigir uma regra existente era preciso encontra-la entre alteracoes
--   recentes, sem busca completa, impacto previo ou historico persistente.
--
-- Solucao:
--   - leitura protegida e paginada de todas as regras;
--   - pre-visualizacao transacional usando o fato_financeiro canonico;
--   - alteracao com chave imutavel, token otimista e ativacao/desativacao;
--   - auditoria central por trigger, incluindo as RPCs antigas;
--   - desfazer exato do ultimo estado compativel;
--   - refresh dos paineis pela fila assincrona existente.
--
-- Riscos controlados:
--   uma regra pode reclassificar varias transacoes vivas e tambem passa a
--   valer para importacoes futuras. Ajustes individuais continuam vencendo o
--   De/Para. raw_historico permanece congelado e nunca e sincronizado por esta
--   rotina. A previa e revertida dentro da propria transacao, sem persistir
--   dados ou auditoria; somente a confirmacao grava o novo estado.
-- =====================================================================

begin;

create table if not exists private.de_para_historico (
  id bigint generated by default as identity primary key,
  regra_id bigint not null,
  chave_tipo text not null,
  chave_valor text not null,
  acao text not null check (acao in ('criar', 'alterar', 'ativar', 'desativar', 'excluir')),
  origem_acao text not null default 'sistema',
  existia_antes boolean not null,
  fornecedor_antes text,
  categoria_antes text,
  ativo_antes boolean,
  atualizado_em_antes timestamptz,
  existia_depois boolean not null,
  fornecedor_depois text,
  categoria_depois text,
  ativo_depois boolean,
  atualizado_em_depois timestamptz,
  alterado_por uuid,
  alterado_em timestamptz not null default now(),
  desfeito_por uuid,
  desfeito_em timestamptz,
  check ((desfeito_por is null) = (desfeito_em is null)),
  check (
    existia_antes
    or (
      fornecedor_antes is null
      and categoria_antes is null
      and ativo_antes is null
      and atualizado_em_antes is null
    )
  ),
  check (
    existia_depois
    or (
      fornecedor_depois is null
      and categoria_depois is null
      and ativo_depois is null
      and atualizado_em_depois is null
    )
  )
);

create index if not exists ix_de_para_historico_regra
  on private.de_para_historico (regra_id, id desc);

create index if not exists ix_de_para_historico_chave
  on private.de_para_historico (chave_tipo, chave_valor, id desc);

alter table private.de_para_historico enable row level security;
revoke all privileges on private.de_para_historico
  from public, anon, authenticated;

comment on table private.de_para_historico is
  'Historico append-only das regras De/Para; exposto somente pela view protegida do gerenciador.';

create or replace function private.token_estado_de_para(
  p_id bigint,
  p_chave_tipo text,
  p_chave_valor text,
  p_fornecedor text,
  p_categoria text,
  p_ativo boolean,
  p_atualizado_em timestamptz
)
returns text
language sql
immutable
security invoker
set search_path = pg_catalog, pg_temp
as $function$
  select md5(
    jsonb_build_array(
      p_id,
      p_chave_tipo,
      p_chave_valor,
      p_fornecedor,
      p_categoria,
      p_ativo,
      extract(epoch from p_atualizado_em)
    )::text
  );
$function$;

revoke all privileges on function private.token_estado_de_para(
  bigint, text, text, text, text, boolean, timestamptz
) from public, anon, authenticated;

create or replace function private.auditar_de_para()
returns trigger
language plpgsql
security definer
set search_path = pg_catalog, public
as $function$
declare
  v_contexto text := coalesce(
    nullif(current_setting('sirfisher.de_para_contexto', true), ''),
    'sistema'
  );
  v_acao text;
  v_regra_id bigint;
  v_chave_tipo text;
  v_chave_valor text;
  v_existia_antes boolean := false;
  v_fornecedor_antes text;
  v_categoria_antes text;
  v_ativo_antes boolean;
  v_atualizado_em_antes timestamptz;
  v_existia_depois boolean := false;
  v_fornecedor_depois text;
  v_categoria_depois text;
  v_ativo_depois boolean;
  v_atualizado_em_depois timestamptz;
begin
  -- A previa e o desfazer usam subfluxos controlados. A previa inteira e
  -- revertida; o desfazer ja marca o evento original com autor e horario.
  if v_contexto in ('preview', 'desfazer') then
    if tg_op = 'DELETE' then
      return old;
    end if;
    return new;
  end if;

  if tg_op <> 'INSERT' then
    v_regra_id := old.id;
    v_chave_tipo := old.chave_tipo;
    v_chave_valor := old.chave_valor;
    v_existia_antes := true;
    v_fornecedor_antes := old.fornecedor;
    v_categoria_antes := old.categoria;
    v_ativo_antes := old.ativo;
    v_atualizado_em_antes := old.atualizado_em;
  end if;

  if tg_op <> 'DELETE' then
    v_regra_id := new.id;
    v_chave_tipo := new.chave_tipo;
    v_chave_valor := new.chave_valor;
    v_existia_depois := true;
    v_fornecedor_depois := new.fornecedor;
    v_categoria_depois := new.categoria;
    v_ativo_depois := new.ativo;
    v_atualizado_em_depois := new.atualizado_em;
  end if;

  if tg_op = 'INSERT' then
    v_acao := 'criar';
  elsif tg_op = 'DELETE' then
    v_acao := 'excluir';
  elsif old.ativo is distinct from new.ativo then
    v_acao := case when new.ativo then 'ativar' else 'desativar' end;
  else
    v_acao := 'alterar';
  end if;

  insert into private.de_para_historico (
    regra_id,
    chave_tipo,
    chave_valor,
    acao,
    origem_acao,
    existia_antes,
    fornecedor_antes,
    categoria_antes,
    ativo_antes,
    atualizado_em_antes,
    existia_depois,
    fornecedor_depois,
    categoria_depois,
    ativo_depois,
    atualizado_em_depois,
    alterado_por,
    alterado_em
  ) values (
    v_regra_id,
    v_chave_tipo,
    v_chave_valor,
    v_acao,
    v_contexto,
    v_existia_antes,
    v_fornecedor_antes,
    v_categoria_antes,
    v_ativo_antes,
    v_atualizado_em_antes,
    v_existia_depois,
    v_fornecedor_depois,
    v_categoria_depois,
    v_ativo_depois,
    v_atualizado_em_depois,
    auth.uid(),
    clock_timestamp()
  );

  if tg_op = 'DELETE' then
    return old;
  end if;
  return new;
end;
$function$;

drop trigger if exists tr_auditar_de_para on public.de_para;
create trigger tr_auditar_de_para
after insert or update or delete on public.de_para
for each row execute function private.auditar_de_para();

revoke all privileges on function private.auditar_de_para()
  from public, anon, authenticated;

